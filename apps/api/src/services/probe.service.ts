export class ProbeService {
  /**
   * Main probe execution: tries yt-dlp first (--dump-single-json --js-runtimes deno,node)
   * and falls back to gallery-dl when yt-dlp returns no media formats or fails.
   */
  public static async probeUrl(rawUrl: string): Promise<NormalizedProbeResponse> {
    const trimmedUrl = rawUrl.trim();
    if (!trimmedUrl) {
      throw new Error('URL parameter is required');
    }

    const platform = detectPlatform(trimmedUrl);

    // For Pinterest pins / boards or Instagram photo carousels, try gallery-dl directly or as primary fallback
    let ytDlpResult: NormalizedProbeResponse | null = null;
    let ytDlpError: Error | null = null;

    try {
      ytDlpResult = await ProbeService.probeWithYtDlp(trimmedUrl, platform);
    } catch (err: any) {
      ytDlpError = err;
    }

    if (ytDlpResult && (ytDlpResult.formats.length > 0 || ytDlpResult.items.length > 0)) {
      return ytDlpResult;
    }

    // Fallback to gallery-dl
    try {
      const galleryResult = await ProbeService.probeWithGalleryDl(trimmedUrl, platform);
      if (galleryResult && (galleryResult.formats.length > 0 || galleryResult.items.length > 0)) {
        return galleryResult;
      }
    } catch (galleryErr: any) {
      // If gallery-dl also fails, throw the original or most descriptive error
      if (ytDlpError) {
        throw new Error(`Media probe failed: ${ytDlpError.message}`);
      }
      throw new Error(`Media probe failed: ${galleryErr.message}`);
    }

    if (ytDlpResult) {
      return ytDlpResult;
    }

    throw new Error('Could not extract any media formats from the provided URL');
  }

  /**
   * Probes URL using yt-dlp with Deno runtime for signature deciphering
   */
  private static async probeWithYtDlp(url: string, platform: SupportedPlatform): Promise<NormalizedProbeResponse> {
    const env = getExecutionEnv();
    const baseArgs = getYtDlpBaseArgs({ includeProgress: false });

    const args = [
      '--dump-single-json',
      '--no-warnings',
      '--no-playlist',
      '--socket-timeout', '30',
      '--js-runtimes', 'deno,node',
      ...baseArgs,
      url,
    ];

    const { stdout } = await execFileAsync('yt-dlp', args, {
      timeout: 35000,
      maxBuffer: 64 * 1024 * 1024,
      windowsHide: true,
      env,
    });

    const parsed = JSON.parse(stdout.trim());
    if (!parsed || typeof parsed !== 'object') {
      throw new Error('yt-dlp returned invalid JSON output');
    }

    const id = String(parsed.id || 'media');
    const title = String(parsed.title || parsed.fulltitle || 'Media Video');
    const author = String(parsed.uploader || parsed.channel || parsed.creator || parsed.artist || 'Unknown Creator');
    const durationSec = typeof parsed.duration === 'number' ? Math.round(parsed.duration) : 0;
    
    // Thumbnail resolution
    let thumbnailUrl = parsed.thumbnail || '';
    if (!thumbnailUrl && Array.isArray(parsed.thumbnails) && parsed.thumbnails.length > 0) {
      thumbnailUrl = parsed.thumbnails[parsed.thumbnails.length - 1].url || '';
    }

    const rawFormats = Array.isArray(parsed.formats) ? parsed.formats : [];
    const isPlaylist = parsed._type === 'playlist' || Array.isArray(parsed.entries);

    // Multi-item / carousel extraction
    const items: NormalizedMediaItem[] = [];
    if (Array.isArray(parsed.entries) && parsed.entries.length > 0) {
      for (const entry of parsed.entries) {
        if (!entry) continue;
        const isVid = Boolean(entry.formats?.length || entry.vcodec !== 'none');
        items.push({
          type: isVid ? 'video' : 'image',
          url: entry.url || entry.webpage_url || url,
          thumbnailUrl: entry.thumbnail,
          width: entry.width,
          height: entry.height,
          ext: entry.ext || (isVid ? 'mp4' : 'jpg'),
        });
      }
    }

    const isCarousel = items.length > 1;

    // Build format matrix up to 8K
    const formatMap = new Map<string, NormalizedFormat>();
    const audioFormats: NormalizedAudioFormat[] = [];

    // Sort audio formats descending by bitrate
    const rawAudioOnly = rawFormats.filter(
      (f: any) => f.acodec && f.acodec !== 'none' && (!f.vcodec || f.vcodec === 'none')
    );
    for (const af of rawAudioOnly) {
      const abr = af.abr || af.tbr || 128;
      const acodec = (af.acodec || 'aac').toLowerCase().split('.')[0];
      const ext = af.ext || (acodec === 'opus' ? 'webm' : 'm4a');
      const estBytes = af.filesize || af.filesize_approx || (durationSec > 0 ? Math.round((abr * 1000 * durationSec) / 8) : undefined);
      
      audioFormats.push({
        formatId: String(af.format_id),
        ext,
        abr: Math.round(abr),
        acodec,
        audioCodec: acodec,
        estBytes,
        url: af.url,
      });
    }

    // Sort audioFormats descending by abr
    audioFormats.sort((a, b) => (b.abr || 0) - (a.abr || 0));

    // Best audio estimated size to add to video-only DASH tracks
    const bestAudioSize = audioFormats[0]?.estBytes || (durationSec > 0 ? Math.round((128 * 1000 * durationSec) / 8) : 0);

    for (const f of rawFormats) {
      const hasVideo = Boolean(f.vcodec && f.vcodec !== 'none' && f.height && f.height > 0);
      if (!hasVideo) continue;

      const height = Number(f.height);
      const width = Number(f.width || Math.round((height * 16) / 9));
      const fps = f.fps ? Math.round(f.fps) : 30;
      const vcodec = String(f.vcodec || 'h264').toLowerCase().split('.')[0];
      const acodec = f.acodec && f.acodec !== 'none' ? String(f.acodec).toLowerCase().split('.')[0] : undefined;
      const requiresMux = !acodec;
      const ext = f.ext || (vcodec.includes('av01') || vcodec.includes('vp9') ? 'webm' : 'mp4');
      const hdr = Boolean(
        (f.dynamic_range && String(f.dynamic_range).toUpperCase().includes('HDR')) ||
        (f.format_note && String(f.format_note).toUpperCase().includes('HDR'))
      );
      const resolution = resolveResolutionLabel(height, width);
      const tbr = f.tbr || f.vbr || 0;

      let estBytes = f.filesize || f.filesize_approx;
      if (!estBytes && durationSec > 0 && tbr > 0) {
        estBytes = Math.round((tbr * 1000 * durationSec) / 8);
      }
      if (estBytes && requiresMux) {
        estBytes += bestAudioSize;
      }

      // Group key: resolution + fpsBucket + hdr + ext
      const fpsBucket = fps >= 50 ? 60 : 30;
      const key = `${resolution}_${fpsBucket}_${hdr ? 'hdr' : 'sdr'}_${ext}`;

      const candidate: NormalizedFormat = {
        formatId: String(f.format_id),
        height,
        width,
        fps,
        hdr,
        vcodec,
        videoCodec: vcodec,
        acodec,
        audioCodec: acodec,
        hasVideo: true,
        hasAudio: Boolean(acodec),
        ext,
        estBytes,
        requiresMux,
        resolution,
        tbr: Math.round(tbr),
        url: f.url,
      };

      const existing = formatMap.get(key);
      if (!existing || (candidate.tbr || 0) > (existing.tbr || 0)) {
        formatMap.set(key, candidate);
      }
    }

    // Sort formats descending by height, then fps, then tbr
    const formats = Array.from(formatMap.values()).sort((a, b) => {
      if (b.height !== a.height) return b.height - a.height;
      if (b.fps !== a.fps) return b.fps - a.fps;
      return (b.tbr || 0) - (a.tbr || 0);
    });

    // Subtitle extraction
    const subtitles: NormalizedSubtitle[] = [];
    const rawSubs = parsed.subtitles || parsed.automatic_captions || {};
    for (const [lang, subList] of Object.entries(rawSubs)) {
      if (Array.isArray(subList) && subList.length > 0) {
        const preferredSub = subList.find((s: any) => s.ext === 'vtt') || subList[0];
        const isAuto = Boolean(parsed.automatic_captions && parsed.automatic_captions[lang]);
        subtitles.push({
          lang,
          language: lang,
          name: preferredSub.name || lang,
          ext: preferredSub.ext || 'vtt',
          url: preferredSub.url,
          isAutoGenerated: isAuto,
        });
      }
    }

    // Map formats to videoStreams
    const videoStreams: MediaStreamDto[] = formats.map((f, idx) => ({
      streamIndex: idx,
      streamType: 'video',
      codec: f.vcodec || 'h264',
      bitrateKbps: f.tbr ? Math.round(f.tbr) : (f.height >= 4320 ? 45000 : f.height >= 2160 ? 25000 : f.height >= 1440 ? 12000 : f.height >= 1080 ? 5000 : 2500),
      formatId: f.formatId,
      width: f.width,
      height: f.height,
      resolutionLabel: f.resolution,
      frameRate: f.fps,
      fps: f.fps,
      hdr: f.hdr,
      estimatedSizeBytes: f.estBytes,
      sizeIsEstimate: true,
      recommended: idx === 0 || f.resolution === '1080p' || f.height === 1080,
      isNativeLossless: true,
      isStreamCopyCandidate: true,
      transcodeRequired: false,
      notes: f.requiresMux ? 'DASH video track - remuxes losslessly with best audio' : 'Direct progressive stream',
      url: f.url,
    }));

    // Map audioFormats to audioStreams
    const audioStreams: MediaStreamDto[] = audioFormats.map((af, idx) => ({
      streamIndex: videoStreams.length + idx,
      streamType: 'audio',
      codec: af.acodec || 'aac',
      bitrateKbps: af.abr ? Math.round(af.abr) : 192,
      formatId: af.formatId,
      sampleRateHz: 48000,
      channels: 2,
      channelLayout: 'stereo',
      estimatedSizeBytes: af.estBytes,
      sizeIsEstimate: true,
      recommended: idx === 0,
      isNativeLossless: true,
      isStreamCopyCandidate: true,
      transcodeRequired: false,
      notes: 'Direct audio stream',
      url: af.url,
    }));

    const streams: MediaStreamDto[] = [...videoStreams, ...audioStreams];

    return {
      platform,
      id,
      url,
      sourceUrl: url,
      title,
      author,
      durationSec,
      durationSeconds: durationSec,
      fileSizeBytes: formats[0]?.estBytes || 0,
      container: formats[0]?.ext || 'mp4',
      permitted: true,
      rightsNote: 'Public media stream available for extraction',
      thumbnailUrl,
      isCarousel,
      items,
      formats,
      audioFormats,
      subtitles,
      videoStreams,
      audioStreams,
      streams,
    };
  }

  /**
   * Probes URL using gallery-dl as fallback for image carousels, Pinterest, etc.
   */
  private static async probeWithGalleryDl(url: string, platform: SupportedPlatform): Promise<NormalizedProbeResponse> {
    const env = getExecutionEnv();
    const args = ['--dump-json', url];

    const { stdout } = await execFileAsync('gallery-dl', args, {
      timeout: 30000,
      maxBuffer: 32 * 1024 * 1024,
      windowsHide: true,
      env,
    });

    const lines = stdout.split('\n').map((l) => l.trim()).filter(Boolean);
    if (lines.length === 0) {
      throw new Error('gallery-dl returned empty output');
    }

    const items: NormalizedMediaItem[] = [];
    let title = 'Media Gallery';
    let author = 'Creator';
    let thumbnailUrl = '';

    for (const line of lines) {
      try {
        const item = JSON.parse(line);
        if (Array.isArray(item) && item.length >= 2) {
          const meta = item[1] || {};
          const itemUrl = item[0] || meta.url || meta.filename;
          const isVideo = Boolean(meta.extension === 'mp4' || meta.extension === 'webm' || (itemUrl && /\.(mp4|webm|mov)$/i.test(itemUrl)));
          
          if (meta.title && title === 'Media Gallery') title = meta.title;
          if (meta.author && author === 'Creator') author = meta.author;
          if (meta.thumbnail && !thumbnailUrl) thumbnailUrl = meta.thumbnail;

          items.push({
            type: isVideo ? 'video' : 'image',
            url: itemUrl,
            thumbnailUrl: meta.thumbnail || (isVideo ? undefined : itemUrl),
            width: meta.width,
            height: meta.height,
            ext: meta.extension || (isVideo ? 'mp4' : 'jpg'),
          });
        } else if (typeof item === 'object') {
          const itemUrl = item.url || item.image || item.filename;
          const isVideo = Boolean(item.extension === 'mp4' || item.extension === 'webm' || (itemUrl && /\.(mp4|webm|mov)$/i.test(itemUrl)));
          if (item.title && title === 'Media Gallery') title = item.title;
          if (item.author || item.user) author = item.author || item.user;
          if (item.thumbnail && !thumbnailUrl) thumbnailUrl = item.thumbnail;

          items.push({
            type: isVideo ? 'video' : 'image',
            url: itemUrl,
            thumbnailUrl: item.thumbnail || (!isVideo ? itemUrl : undefined),
            width: item.width,
            height: item.height,
            ext: item.extension || (isVideo ? 'mp4' : 'jpg'),
          });
        }
      } catch {}
    }

    if (!thumbnailUrl && items.length > 0) {
      thumbnailUrl = items[0].thumbnailUrl || items[0].url;
    }

    const isCarousel = items.length > 1;

    // Build default formats from extracted items
    const formats: NormalizedFormat[] = [];
    let fmtIndex = 1;
    for (const it of items) {
      if (it.type === 'video') {
        const h = it.height || 1080;
        formats.push({
          formatId: `gallery_${fmtIndex++}`,
          height: h,
          width: it.width || 1920,
          fps: 30,
          hdr: false,
          vcodec: 'h264',
          videoCodec: 'h264',
          acodec: 'aac',
          audioCodec: 'aac',
          hasVideo: true,
          hasAudio: true,
          ext: it.ext || 'mp4',
          requiresMux: false,
          resolution: resolveResolutionLabel(h, it.width),
          url: it.url,
        });
      }
    }

    const videoStreams: MediaStreamDto[] = formats.map((f, idx) => ({
      streamIndex: idx,
      streamType: 'video',
      codec: f.vcodec || 'h264',
      bitrateKbps: f.tbr ? Math.round(f.tbr) : 5000,
      formatId: f.formatId,
      width: f.width,
      height: f.height,
      resolutionLabel: f.resolution,
      frameRate: f.fps,
      fps: f.fps,
      hdr: f.hdr,
      estimatedSizeBytes: f.estBytes,
      sizeIsEstimate: true,
      recommended: idx === 0,
      isNativeLossless: true,
      isStreamCopyCandidate: true,
      transcodeRequired: false,
      notes: 'Direct gallery media stream',
      url: f.url,
    }));

    const audioStreams: MediaStreamDto[] = [];
    const streams: MediaStreamDto[] = [...videoStreams];

    return {
      platform,
      id: `gallery_${Date.now()}`,
      url,
      sourceUrl: url,
      title,
      author,
      durationSec: 0,
      durationSeconds: 0,
      fileSizeBytes: formats[0]?.estBytes || 0,
      container: formats[0]?.ext || 'mp4',
      permitted: true,
      rightsNote: 'Public media stream available for extraction',
      thumbnailUrl,
      isCarousel,
      items,
      formats,
      audioFormats: [],
      subtitles: [],
      videoStreams,
      audioStreams,
      streams,
    };
  }
}
