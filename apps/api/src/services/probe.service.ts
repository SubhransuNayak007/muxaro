/**
 * MUXARO Media Processing Platform - 8K Multi-Platform Probe Service
 * 
 * Extracts and normalizes media metadata up to 8K using:
 * 1. yt-dlp nightly + yt-dlp-ejs + Deno runtime (--dump-single-json --js-runtimes deno,node)
 * 2. gallery-dl fallback for Pinterest, Instagram carousels, and image/gallery platforms
 * 
 * Supported Platforms:
 * - YouTube (up to 8K AV1/VP9/HDR + audio streams + subtitles)
 * - Instagram (Reels, Videos, Carousel posts)
 * - X/Twitter (multi-bitrate MP4 streams)
 * - Facebook (HD bestvideo+bestaudio)
 * - Pinterest (Pins, Videos, Carousel boards)
 * - TikTok (Watermark-free HD videos)
 * - Reddit (DASH video + audio)
 * - Vimeo (up to 4K/8K)
 * - Direct / Generic media URLs
 */

import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import os from 'node:os';
import fs from 'node:fs';
import { getYtDlpBaseArgs } from './turboflow.service.js';

const execFileAsync = promisify(execFile);

export type SupportedPlatform =
  | 'youtube'
  | 'instagram'
  | 'twitter'
  | 'facebook'
  | 'pinterest'
  | 'tiktok'
  | 'reddit'
  | 'vimeo'
  | 'generic';

export interface NormalizedMediaItem {
  type: 'video' | 'image';
  url: string;
  thumbnailUrl?: string;
  width?: number;
  height?: number;
  ext?: string;
}

export interface NormalizedFormat {
  formatId: string;
  height: number;
  width?: number;
  fps: number;
  hdr: boolean;
  vcodec: string;
  videoCodec?: string;
  acodec?: string;
  audioCodec?: string;
  hasVideo: boolean;
  hasAudio: boolean;
  ext: string;
  estBytes?: number;
  requiresMux: boolean;
  resolution: string; // '8K', '4K', '1440p', '1080p', '720p', '480p', '360p', '240p'
  tbr?: number;
  url?: string;
}

export interface NormalizedAudioFormat {
  formatId: string;
  ext: string;
  abr?: number;
  acodec: string;
  audioCodec?: string;
  estBytes?: number;
  url?: string;
}

export interface NormalizedSubtitle {
  lang: string;
  language: string;
  name?: string;
  ext: string;
  url?: string;
  isAutoGenerated?: boolean;
}

export interface MediaStreamDto {
  streamIndex: number;
  streamType: 'video' | 'audio';
  codec: string;
  bitrateKbps: number;
  formatId?: string;
  width?: number;
  height?: number;
  resolutionLabel?: string; // '8K', '4K', '1440p', '1080p', '720p', '480p', '360p'
  sampleRateHz?: number;
  channels?: number;
  channelLayout?: string;
  frameRate?: number;
  fps?: number;
  hdr?: boolean;
  estimatedSizeBytes?: number;
  sizeIsEstimate?: boolean;
  recommended?: boolean;
  isNativeLossless?: boolean;
  isStreamCopyCandidate: boolean;
  transcodeRequired: boolean;
  notes?: string;
  url?: string;
}

export interface NormalizedProbeResponse {
  platform: SupportedPlatform;
  id: string;
  url: string;
  sourceUrl: string;
  title: string;
  author: string;
  durationSec: number;
  durationSeconds: number;
  fileSizeBytes: number;
  container: string;
  permitted: boolean;
  rightsNote: string;
  thumbnailUrl: string;
  isCarousel: boolean;
  items: NormalizedMediaItem[];
  formats: NormalizedFormat[];
  audioFormats: NormalizedAudioFormat[];
  subtitles: NormalizedSubtitle[];
  videoStreams: MediaStreamDto[];
  audioStreams: MediaStreamDto[];
  streams: MediaStreamDto[];
}

export function detectPlatform(url: string): SupportedPlatform {
  try {
    const parsed = new URL(url);
    const host = parsed.hostname.toLowerCase();
    if (host.includes('youtube.com') || host.includes('youtu.be')) return 'youtube';
    if (host.includes('instagram.com')) return 'instagram';
    if (host.includes('twitter.com') || host.includes('x.com')) return 'twitter';
    if (host.includes('facebook.com') || host.includes('fb.watch')) return 'facebook';
    if (host.includes('pinterest.com') || host.includes('pin.it')) return 'pinterest';
    if (host.includes('tiktok.com')) return 'tiktok';
    if (host.includes('reddit.com') || host.includes('redd.it')) return 'reddit';
    if (host.includes('vimeo.com')) return 'vimeo';
  } catch {}
  return 'generic';
}

function resolveResolutionLabel(height: number, width?: number): string {
  if (height >= 4320 || (width && width >= 7680)) return '8K';
  if (height >= 2160 || (width && width >= 3840)) return '4K';
  if (height >= 1440 || (width && width >= 2560)) return '1440p';
  if (height >= 1080 || (width && width >= 1920)) return '1080p';
  if (height >= 720) return '720p';
  if (height >= 480) return '480p';
  if (height >= 360) return '360p';
  if (height >= 240) return '240p';
  return `${height}p`;
}

